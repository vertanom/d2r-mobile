#include "../../host/dm.h"

typedef struct { CGFloat r, g, b, tint, alpha, thick, size; } aim_look;
static aim_look g_look = { 199 / 255.0, 179 / 255.0, 119 / 255.0, 0, 0.85, 2, 1 };   // 缺省：原版金字色（只在描线时用）、不染色、圆环加粗一倍（Victor 2026-11-05：原图那一圈太细） | defaults: the original gold text color (only used by the outline), no tint, ring twice as thick (Victor 2026-11-05: the original band is too thin)
static CGImageRef g_ring, g_tip; static CGFloat g_ring_out = 1;   // 处理好的圆环 / 尖；g_ring_out = 圆环外沿半径占图半边的比例 | processed ring / tip; g_ring_out = the ring's outer edge radius as a fraction of half the image
static int g_gen;   // 外观换了一次就加一（前端据此重设图层内容） | bumped whenever the looks change (the layers' contents are reset by it)
static uint8_t *g_ring_px, *g_tip_px; static int g_ring_n, g_tip_n;   // 同一份图的像素（地面贴花上传用，dm_aim_art_with） | the same images' pixels (uploaded by the ground decal, dm_aim_art_with)
static pthread_mutex_t g_art_mu = PTHREAD_MUTEX_INITIALIZER;   // 外观重读与取像素：前端主线程与画线程（贴花）都会来 | looks reload and pixel taking: both the front end's main thread and the render thread (decal) come here

static CGColorRef rgba(CGFloat a) { return (CGColorRef)CFAutorelease(CGColorCreateSRGB(g_look.r, g_look.g, g_look.b, a)); }
static void ground_ellipse(CGMutablePathRef p, CGPoint c, CGFloat k, CGFloat r) {   // 地上半径 r 格的圆 → 画面椭圆：半轴 16√2·k·r、8√2·k·r | a circle of r cells on the ground -> screen ellipse: semi-axes 16√2·k·r, 8√2·k·r
    CGFloat a = 16 * M_SQRT2 * k * r, b = 8 * M_SQRT2 * k * r; CGPathAddEllipseInRect(p, NULL, CGRectMake(c.x - a, c.y - b, 2 * a, 2 * b));
}
static CGRect ground_box(CGPoint c, CGFloat k, CGFloat r) { CGFloat a = 16 * M_SQRT2 * k * r, b = 8 * M_SQRT2 * k * r; return CGRectMake(c.x - a, c.y - b, 2 * a, 2 * b); }
static CGPoint ground_pt(CGPoint f, CGFloat H, float cx, float cy) { float px, py; dm_aim_cells_to_px(cx, cy, (float)H, &px, &py); return CGPointMake(f.x + px, f.y + py); }

// ---- 素材与外观 | Art and looks ----
static NSString *custom_path(NSString *name) { const char *dm_custom_dir(void); const char *d = dm_custom_dir(); return d ? [@(d) stringByAppendingPathComponent:name] : nil; }
static NSString *art_path(NSString *name) {   // 自定义目录优先，再找包里的 aim/ | the custom directory first, then aim/ in the package
    NSString *c = custom_path(name); if (c && [NSFileManager.defaultManager fileExistsAtPath:c]) return c;
    NSString *b = [[NSBundle.mainBundle.resourcePath stringByAppendingPathComponent:@"aim"] stringByAppendingPathComponent:name];
    return [NSFileManager.defaultManager fileExistsAtPath:b] ? b : nil;
}
static CGImageRef load_png(NSString *p) {
    if (!p) return NULL; CGImageSourceRef s = CGImageSourceCreateWithURL((__bridge CFURLRef)[NSURL fileURLWithPath:p], NULL); if (!s) return NULL;
    CGImageRef im = CGImageSourceCreateImageAtIndex(s, 0, NULL); CFRelease(s); return im;
}
// 图 → 预乘 RGBA8 方块（边长 n，最大 512） | image -> premultiplied RGBA8 square (side n, at most 512)
static uint8_t *pixels(CGImageRef im, int n) {
    uint8_t *px = calloc((size_t)n * n, 4); CGColorSpaceRef cs = CGColorSpaceCreateWithName(kCGColorSpaceSRGB);
    CGContextRef c = CGBitmapContextCreate(px, n, n, 8, n * 4, cs, (CGBitmapInfo)kCGImageAlphaPremultipliedLast); CGColorSpaceRelease(cs);
    CGContextSetInterpolationQuality(c, kCGInterpolationHigh); CGContextDrawImage(c, CGRectMake(0, 0, n, n), im); CGContextRelease(c); return px;
}
static CGImageRef image_of(uint8_t *px, int n) {
    CGColorSpaceRef cs = CGColorSpaceCreateWithName(kCGColorSpaceSRGB);
    CGContextRef c = CGBitmapContextCreate(px, n, n, 8, n * 4, cs, (CGBitmapInfo)kCGImageAlphaPremultipliedLast); CGColorSpaceRelease(cs);
    CGImageRef im = CGBitmapContextCreateImage(c); CGContextRelease(c); return im;
}
// 染色：按亮度乘上设定色，tint 是和原色的混合比例（预乘值上算，透明度不变） | tint: luminance times the chosen color, tint = the mix with the original colors (done on premultiplied values, alpha unchanged)
static void tint_px(uint8_t *px, int n) {
    if (g_look.tint <= 0) return; CGFloat t = MIN(1, g_look.tint), col[3] = { g_look.r, g_look.g, g_look.b };
    for (int i = 0; i < n * n; i++) { uint8_t *p = px + 4 * i; CGFloat L = (0.30 * p[0] + 0.59 * p[1] + 0.11 * p[2]) * 1.8;
        for (int c = 0; c < 3; c++) { CGFloat v = p[c] * (1 - t) + MIN(p[3], L * col[c]) * t; p[c] = (uint8_t)lround(MIN(p[3], v)); } }
}
// 圆环加粗：先按半径量出那一圈（透明度过峰值四分之一的内外半径），再按 thick 倍把这一圈沿半径拉宽重采样（外沿不超出图）。
// 换谁的圆环图都能用（AI 改过的也一样），返回外沿半径占图半边的比例
// Ring thickening: first measure the band by radius (inner and outer radius where alpha passes a quarter of the peak), then resample it stretched along the radius by thick (the outer edge stays inside the image).
// Works with anyone's ring image (AI-restyled ones too); returns the outer edge radius as a fraction of half the image
static CGFloat thicken(uint8_t **ppx, int n) {
    uint8_t *px = *ppx; int nb = n / 2 + 2; double *sum = calloc((size_t)nb, sizeof *sum), *cnt = calloc((size_t)nb, sizeof *cnt); double h = n / 2.0;
    for (int y = 0; y < n; y++) for (int x = 0; x < n; x++) { int r = (int)hypot(x + 0.5 - h, y + 0.5 - h); if (r < nb) { sum[r] += px[4 * (y * n + x) + 3]; cnt[r] += 1; } }
    double peak = 0; for (int r = 0; r < nb; r++) { if (cnt[r]) sum[r] /= cnt[r]; if (sum[r] > peak) peak = sum[r]; }
    int r0 = -1, r1 = -1; for (int r = 0; r < nb; r++) if (sum[r] > peak / 4) { if (r0 < 0) r0 = r; r1 = r; }
    free(sum); free(cnt);
    if (r0 < 0 || r1 <= r0) return 1;
    double mid = (r0 + r1) / 2.0, half = (r1 - r0) / 2.0 + 1, k = MAX(0.3, MIN(4.0, g_look.thick)), nh = half * k, nmid = MIN(mid, h - 1 - nh);
    if (nmid - nh < 1) nmid = nh + 1;
    if (k == 1) return (r1 + 1) / h;
    uint8_t *o = calloc((size_t)n * n, 4);
    for (int y = 0; y < n; y++) for (int x = 0; x < n; x++) {
        double dx = x + 0.5 - h, dy = y + 0.5 - h, r = hypot(dx, dy); if (r < 1e-6) continue;
        double sr = mid + (r - nmid) / k; if (sr < 0 || sr > h) continue;
        double sx = h + dx / r * sr - 0.5, sy = h + dy / r * sr - 0.5; int ix = (int)floor(sx), iy = (int)floor(sy); double fx = sx - ix, fy = sy - iy;
        for (int c = 0; c < 4; c++) { double v = 0;   // 双线性 | bilinear
            for (int j = 0; j < 2; j++) for (int i = 0; i < 2; i++) { int xx = ix + i, yy = iy + j; if (xx < 0 || yy < 0 || xx >= n || yy >= n) continue;
                v += px[4 * (yy * n + xx) + c] * (i ? fx : 1 - fx) * (j ? fy : 1 - fy); }
            o[4 * (y * n + x) + c] = (uint8_t)lround(MIN(255, v)); } }
    free(px); *ppx = o; return MIN(1, (nmid + nh) / h);
}
static double ftime(NSString *p) { struct stat st; return p && !stat(p.fileSystemRepresentation, &st) ? st.st_mtimespec.tv_sec + st.st_mtimespec.tv_nsec * 1e-9 : 0; }
static void read_look(NSString *p) {
    aim_look l = { 199 / 255.0, 179 / 255.0, 119 / 255.0, 0, 0.85, 2, 1 };
    NSString *t = p ? [NSString stringWithContentsOfFile:p encoding:NSUTF8StringEncoding error:nil] : nil;
    for (NSString *line in [t componentsSeparatedByCharactersInSet:NSCharacterSet.newlineCharacterSet]) {
        NSArray *kv = [line componentsSeparatedByString:@"="]; if (kv.count != 2 || [line hasPrefix:@"#"]) continue;
        NSString *k = [kv[0] stringByTrimmingCharactersInSet:NSCharacterSet.whitespaceCharacterSet], *v = [kv[1] stringByTrimmingCharactersInSet:NSCharacterSet.whitespaceCharacterSet];
        if ([k isEqualToString:@"color"]) { unsigned x = 0; if ([[NSScanner scannerWithString:v] scanHexInt:&x]) { l.r = (x >> 16 & 255) / 255.0; l.g = (x >> 8 & 255) / 255.0; l.b = (x & 255) / 255.0; } }
        else if ([k isEqualToString:@"tint"]) l.tint = MAX(0, MIN(1, v.doubleValue));
        else if ([k isEqualToString:@"alpha"]) l.alpha = MAX(0.05, MIN(1, v.doubleValue));
        else if ([k isEqualToString:@"thick"]) l.thick = MAX(0.3, MIN(4, v.doubleValue));
        else if ([k isEqualToString:@"size"]) l.size = MAX(0.5, MIN(2.5, v.doubleValue));
    }
    g_look = l;
}
// 每半秒看一次 aim_hud.txt 与两张图的修改时间，变了就重读重做 | every half second check the modification times of aim_hud.txt and the two images; reload and rebuild on change
static void refresh_art(void) {
    static CFTimeInterval next; static double seen[3] = { -1, -1, -1 }; static NSString *seen_p[2];
    CFTimeInterval now = CACurrentMediaTime(); if (now < next) return; next = now + 0.5;
    NSString *cp = custom_path(@"aim_hud.txt"), *rp = art_path(@"aim_ring.png"), *tp = art_path(@"aim_tip.png");
    double t[3] = { ftime(cp), ftime(rp), ftime(tp) };
    if (t[0] == seen[0] && t[1] == seen[1] && t[2] == seen[2] && (rp == seen_p[0] || [rp isEqual:seen_p[0]]) && (tp == seen_p[1] || [tp isEqual:seen_p[1]])) return;
    memcpy(seen, t, sizeof t); seen_p[0] = rp; seen_p[1] = tp;
    read_look(cp);
    if (g_ring) CGImageRelease(g_ring); if (g_tip) CGImageRelease(g_tip); g_ring = g_tip = NULL; g_ring_out = 1;
    free(g_ring_px); free(g_tip_px); g_ring_px = g_tip_px = NULL; g_ring_n = g_tip_n = 0;
    CGImageRef r = load_png(rp), tip = load_png(tp);
    if (r) { int n = (int)MIN(512, MAX(CGImageGetWidth(r), CGImageGetHeight(r))); uint8_t *px = pixels(r, n); g_ring_out = thicken(&px, n); tint_px(px, n); g_ring = image_of(px, n); g_ring_px = px; g_ring_n = n; CGImageRelease(r); }
    if (tip) { int n = (int)MIN(256, MAX(CGImageGetWidth(tip), CGImageGetHeight(tip))); uint8_t *px = pixels(tip, n); tint_px(px, n); g_tip = image_of(px, n); g_tip_px = px; g_tip_n = n; CGImageRelease(tip); }
    g_gen++;
    LOG("瞄准指示：外观重载（圆环 %s、尖 %s；染色 %.2f 不透明 %.2f 粗细 %.2f 大小 %.2f）", rp ? rp.lastPathComponent.UTF8String : "描线", tp ? tp.lastPathComponent.UTF8String : "描线", g_look.tint, g_look.alpha, g_look.thick, g_look.size);
}

int dm_aim_art_with(int have, void (*fn)(const dm_aim_art *a, void *ctx), void *ctx) {
    pthread_mutex_lock(&g_art_mu); refresh_art(); int gen = g_gen;
    if (gen != have) { dm_aim_art a = { g_ring_px, g_tip_px, g_ring_n, g_tip_n, (float)g_ring_out, (float)g_look.alpha, (float)g_look.size }; fn(&a, ctx); }
    pthread_mutex_unlock(&g_art_mu); return gen;
}

// 尖：一张朝上的图放到地面平面里，朝 d。图上的 x / y（格）→ 地面 x·e − y·d（e ⊥ d）→ 画面（dm_aim_cells_to_px 的线性部分）
// Tip: an upward image placed in the ground plane, pointing toward d. Image x / y (cells) -> ground x·e − y·d (e ⊥ d) -> picture (the linear part of dm_aim_cells_to_px)
static void place_tip(CALayer *l, CGPoint c, CGFloat k, float dx, float dy, CGFloat side) {
    float ex = -dy, ey = dx; CGFloat u = side / 100;
    l.bounds = CGRectMake(0, 0, 100, 100); l.position = c;
    l.affineTransform = CGAffineTransformMake((ex - ey) * 16 * k * u, (ex + ey) * 8 * k * u, -(dx - dy) * 16 * k * u, -(dx + dy) * 8 * k * u, 0, 0);
}

void dm_aim_hud_draw(DmAimView *host, CGRect wr, BOOL hide) {
    static CALayer *box, *around, *ring, *tipi, *landi; static CAShapeLayer *disc, *tip, *land, *mask; static int gen = -1;
    dm_aim_view v; int kind = hide ? 0 : dm_aim_view_get(&v);
    if (!box) { if (!kind) return;
        box = [CALayer layer];
#if TARGET_OS_OSX
        box.geometryFlipped = YES;   // AppKit 宿主左下原点，子层按左上算（同 dm_rift_hud.m） | AppKit hosts have a bottom-left origin; children are laid out top-left (same as dm_rift_hud.m)
#endif
        around = [CALayer layer]; disc = [CAShapeLayer layer]; tip = [CAShapeLayer layer]; land = [CAShapeLayer layer]; mask = [CAShapeLayer layer];
        ring = [CALayer layer]; tipi = [CALayer layer]; landi = [CALayer layer];
        mask.fillRule = kCAFillRuleEvenOdd; mask.fillColor = CGColorGetConstantColor(kCGColorBlack); tip.strokeColor = NULL;
        for (CALayer *l in @[ring, tipi, landi]) { l.contentsGravity = kCAGravityResize; l.minificationFilter = kCAFilterTrilinear; }
        [around addSublayer:disc]; [around addSublayer:ring]; [around addSublayer:tip]; [around addSublayer:tipi]; around.mask = mask;   // 遮罩只管人物脚下那一圈，落点圈不挖 | the mask only applies to the ring under the character, not to the landing circle
        [box addSublayer:around]; [box addSublayer:land]; [box addSublayer:landi]; [host.layer addSublayer:box]; }
    pthread_mutex_lock(&g_art_mu); refresh_art();   // 锁到画完：画线程（贴花）重读外观会换掉 g_ring / g_tip | held until drawn: the render thread (decal) reloading the looks would swap g_ring / g_tip
    if (kind && dm_aim_decal_live()) kind = 0;   // 地面贴花在画（Metal 后端，nvn_mtl.m）：覆盖层不画 | the ground decal is drawing (Metal backend, nvn_mtl.m): the overlay stays off
    [CATransaction begin]; [CATransaction setDisableActions:YES];
    box.hidden = !kind;
    if (gen != g_gen) { gen = g_gen;   // 外观变了：换图、换色 | looks changed: new images, new colors
        ring.contents = landi.contents = (__bridge id)g_ring; tipi.contents = (__bridge id)g_tip;
        disc.fillColor = rgba(0.08); disc.strokeColor = rgba(0.6); tip.fillColor = rgba(0.85); land.fillColor = rgba(0.10); land.strokeColor = rgba(0.7);
        box.opacity = (float)g_look.alpha; }
    if (kind) {
        CGFloat W = wr.size.width, H = wr.size.height, k = H * 0.00206, lw = MAX(1.0, H / 540) * 2.5 * g_look.thick, R = 1.4 * g_look.size;
        box.frame = wr;   // 两端都是游戏画面在宿主视图里的矩形；Mac 靠 geometryFlipped 让里面按左上算 | on both ends the game picture's rectangle in the host view; on the Mac geometryFlipped makes the inside top-left
        CGRect all = CGRectMake(0, 0, W, H);
        around.frame = disc.frame = tip.frame = land.frame = mask.frame = all; disc.lineWidth = land.lineWidth = lw;
        CGPoint f = CGPointMake(v.fx * W, v.fy * H);
        CGMutablePathRef dp = CGPathCreateMutable(), tp = CGPathCreateMutable(), lp = CGPathCreateMutable(), mp = CGPathCreateMutable();
        int hasd = (kind & 1) && (v.dx || v.dy);
        ring.hidden = !(kind & 1) || !g_ring; tipi.hidden = !hasd || !g_tip; landi.hidden = !(kind & 2) || !g_ring;
        if (kind & 1) {
            if (g_ring) ring.frame = ground_box(f, k, R / g_ring_out); else ground_ellipse(dp, f, k, R);
            if (hasd) {
                if (g_tip) place_tip(tipi, ground_pt(f, H, v.dx * (R + 0.55f), v.dy * (R + 0.55f)), k, v.dx, v.dy, 1.0 * g_look.size);
                else { float nx = -v.dy, ny = v.dx;   // 地面上的垂直方向 | perpendicular on the ground
                    CGPoint a = ground_pt(f, H, v.dx * (R + 0.85), v.dy * (R + 0.85)), b = ground_pt(f, H, v.dx * (R + 0.1) + nx * 0.42, v.dy * (R + 0.1) + ny * 0.42), c = ground_pt(f, H, v.dx * (R + 0.1) - nx * 0.42, v.dy * (R + 0.1) - ny * 0.42);
                    CGPathMoveToPoint(tp, NULL, a.x, a.y); CGPathAddLineToPoint(tp, NULL, b.x, b.y); CGPathAddLineToPoint(tp, NULL, c.x, c.y); CGPathCloseSubpath(tp); } } }
        if (kind & 2) { CGPoint lc = ground_pt(f, H, v.lx, v.ly); CGFloat lr = v.lr > 0 ? v.lr : 1;
            if (g_ring) landi.frame = ground_box(lc, k, lr / g_ring_out); else ground_ellipse(lp, lc, k, lr); }
        CGPathAddRect(mp, NULL, all); CGPathAddRect(mp, NULL, CGRectMake(f.x - 15 * k, f.y - 92 * k, 30 * k, 92 * k + lw));   // 挖掉人物：宽约 30、高约 92 经典像素 | cut out the character: about 30 wide, 92 high in classic pixels
        disc.path = dp; tip.path = tp; land.path = lp; mask.path = mp; CGPathRelease(dp); CGPathRelease(tp); CGPathRelease(lp); CGPathRelease(mp);
    }
    [CATransaction commit];
    pthread_mutex_unlock(&g_art_mu);
}
