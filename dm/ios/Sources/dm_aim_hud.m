// 手柄瞄准指示：数据由 dm/host/hle_private_aim.c 出（dm_aim_view_get），两端前端刷新覆盖层时调用（同 dm_rift_hud.m）。
//   人物脚下一圈地面上的淡圆盘（地上半径 1.4 格，斜视角下扁），朝瞄准方向伸出一个三角尖；尖与圈都在地面平面里算再投到画面，所以贴地。
//   人物身上不画：圈过人物身后的那段（脚底往上一个人高、左右半个人宽）被遮罩挖掉，看起来是从人后面绕过去。
//   「松开才放」按住瞄的时候再加落点圈（位移类 1 格、落点类 2.5 格）。没有连线（Victor 2026-11-04：信息太多）。
//   圈与尖是贴图（Victor 2026-11-05：要粗一点、像原版美术，不要纯色）：缺省取原版表情轮盘的鎏金圆环与指针（tools/gen_aim_art.py 生成，包里 aim/），
//   自定义目录里有 aim_ring.png / aim_tip.png 就用那两张（玩家拿去给别的 AI 改过画风再放回来）；都没有 = 原先的金色描线。
//   外观设定在自定义目录 aim_hud.txt（「手柄 → 瞄准指示…」窗口写，aimhud_mac.m）：color = 染色（十六进制 RGB），tint = 染色强度 0–1（0 = 原图颜色），
//   alpha = 不透明度，thick = 圆环粗细倍数（按半径重采样圆环那一圈，任何人给的圆环图都适用），size = 圈的大小倍数。文件或图一变（修改时间）就重载，边玩边调
// Controller aim indicator: data comes from dm/host/hle_private_aim.c (dm_aim_view_get); both front ends call it while refreshing their overlays (same as dm_rift_hud.m).
//   A faint disc on the ground around the character's feet (1.4 cells radius on the ground, flattened by the isometric view), with a triangular tip toward the aim direction; tip and ring are computed in the ground plane and projected, so they lie flat.
//   Nothing is drawn over the character: the part of the ring passing behind the character (from the feet up one character height, half a character width to each side) is cut out by a mask, so it reads as going around behind them.
//   While holding to aim under "cast on release" a landing circle is added (movement 1 cell, ground zone 2.5 cells). No connecting line (Victor 2026-11-04: too much information).
//   Ring and tip are textures (Victor 2026-11-05: thicker, in the original art's style, not a flat color): by default the original emote wheel's gilded ring and pointer (generated by tools/gen_aim_art.py, aim/ in the package);
//   if the custom directory has aim_ring.png / aim_tip.png those are used (players restyle them with another AI and put them back); with neither = the former gold outline.
//   Looks are set in aim_hud.txt in the custom directory (written by the "Controller -> Aim Indicator..." window, aimhud_mac.m): color = tint (hex RGB), tint = tint strength 0-1 (0 = the image's own colors),
//   alpha = opacity, thick = ring thickness factor (resamples the ring's band by radius, so it works with anyone's ring image), size = ring size factor. Reloaded whenever the file or an image changes (modification time), so it can be tuned while playing
#import "dm_aim_hud.h"
#import <QuartzCore/QuartzCore.h>
#import <ImageIO/ImageIO.h>
